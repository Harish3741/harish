export const CHAR_W = 5;
export const CHAR_H = 7;

export function textWidth(str, tracking = 1) {
  if (!str.length) return 0;
  return str.length * (CHAR_W + tracking) - tracking;
}

/**
 * Draw a string as bitmap pixels.
 * @param {CanvasRenderingContext2D} ctx
 * @param {string} str
 * @param {number} x left edge, in logical pixels
 * @param {number} y top edge, in logical pixels
 * @param {object} [opts] colour, tracking, scale, shadow colour
 */
export function drawText(ctx, str, x, y, opts = {}) {
  const color = opts.color || '#3B2A22';
  const tracking = opts.tracking ?? 1;
  const scale = opts.scale ?? 1;
  const upper = String(str).toUpperCase();

  if (opts.shadow) {
    drawText(ctx, str, x, y + scale, { ...opts, color: opts.shadow, shadow: null });
  }

  ctx.fillStyle = color;
  let cx = x;
  for (const ch of upper) {
    const glyph = G[ch] || G['?'];
    for (let gy = 0; gy < CHAR_H; gy++) {
      const row = glyph[gy];
      for (let gx = 0; gx < CHAR_W; gx++) {
        if (row[gx] === '#') {
          ctx.fillRect(cx + gx * scale, y + gy * scale, scale, scale);
        }
      }
    }
    cx += (CHAR_W + tracking) * scale;
  }
}

/** Draw a string centred on `cx`. */
export function drawTextCentered(ctx, str, cx, y, opts = {}) {
  const scale = opts.scale ?? 1;
  const tracking = opts.tracking ?? 1;
  const w = textWidth(String(str), tracking) * scale;
  drawText(ctx, str, Math.round(cx - w / 2), y, opts);
}
